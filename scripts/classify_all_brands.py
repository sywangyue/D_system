    jufair_url_to_cat = {}
    jufair_rows = jufair_conn.execute(
        "SELECT source_url, industry FROM raw_jufair WHERE industry IS NOT NULL AND industry != ''"
    ).fetchall()
    for row in jufair_rows:
        jufair_cat = extract_jufair_category(row["industry"])
        if jufair_cat:
            l1, l2 = jufair_cat_to_l1l2(jufair_cat)
            if l1:
                jufair_url_to_cat[row["source_url"]] = (l1, l2, jufair_cat)

    log.info(f"  Jufair 分类映射: {len(jufair_url_to_cat)} URLs → {len(set(v[0] for v in jufair_url_to_cat.values()))} 个 l1 类别")
    if _unknown_jufair_cats:
        # jufair 新增了分类值 —— 这些展会只能靠品牌名兜底，需要补进 JUFAIR_CAT_TO_L1L2
        log.warning(f"  映射表缺 {len(_unknown_jufair_cats)} 个 jufair 分类: "
                    f"{'、'.join(sorted(_unknown_jufair_cats)[:20])}")

    # ── Step 2: Match jufair-sourced brands via data_provenance ──
    log.info("Step 2: 匹配 jufair 来源品牌...")
    brand_l1l2: dict[str, tuple[str, str]] = {}  # brand_id → (l1, l2)

    dp_rows = conn.execute("""
        SELECT DISTINCT dp.brand_id, dp.source_url
        FROM data_provenance dp
        WHERE dp.source_site = 'jufair'
    """).fetchall()

    jufair_matched = 0
    for row in dp_rows:
        bid = row["brand_id"]
        url = row["source_url"]
        if url in jufair_url_to_cat and bid not in brand_l1l2:
            l1, l2, _ = jufair_url_to_cat[url]
            brand_l1l2[bid] = (l1, l2)
            jufair_matched += 1

    log.info(f"  Jufair 来源匹配: {jufair_matched} 品牌有行业分类")

    # ── Step 3: Keyword match for remaining brands (cnexpo + orphans) ──
    log.info("Step 3: 关键词匹配剩余品牌...")
    # only_empty：只处理尚无 industry_l1 的品牌，不动已有分类。
    # 详情补爬让 industry_raw 大规模填充后，jufair 官方分类会对 720 个已分类品牌
    # 提出改判，但抽查显示好坏参半（如「台北电脑展 科技+→生活方式」明显退化），
    # 属映射表质量问题，需单独评审，不应随例行补分类一起冲掉。
    if only_empty:
        all_brands = conn.execute(
            "SELECT brand_id, name_cn FROM exhibition_brand "
            "WHERE industry_l1 IS NULL OR TRIM(industry_l1) = ''"
        ).fetchall()
    else:
        all_brands = conn.execute(
            "SELECT brand_id, name_cn FROM exhibition_brand"
        ).fetchall()

    keyword_matched = 0
    unmatched = 0

    updates: list[tuple[str, str, str]] = []  # (l1, l2, brand_id)

    for row in all_brands:
        bid = row["brand_id"]
        name_cn = row["name_cn"]

        if bid in brand_l1l2:
            # Already has jufair classification
            l1, l2 = brand_l1l2[bid]
        else:
            l1, l2 = classify_by_name(name_cn)
            if l1:
                brand_l1l2[bid] = (l1, l2)
                keyword_matched += 1
            else:
                unmatched += 1
                # log.warning(f"  未匹配: {bid} — {name_cn[:60]}")
                continue

        if l1:
            updates.append((l1, l2 or "", bid))

    log.info(f"  关键词匹配: {keyword_matched} 品牌")
    log.info(f"  未匹配: {unmatched} 品牌")

    # ── Step 4: Apply updates ──
    total_matched = len(updates)
    log.info(f"Step 4: {'[DRY-RUN] ' if dry_run else ''}写入 {total_matched} 条更新...")

    if not dry_run:
        conn.execute("BEGIN")
        for l1, l2, bid in updates:
            conn.execute(
                "UPDATE exhibition_brand SET industry_l1 = ?, industry_l2 = ? WHERE brand_id = ?",
                (l1, l2, bid),
            )
        conn.commit()
        log.info("  已提交变更到数据库")

        # ── Verify ──
        empty_l1 = conn.execute(
            "SELECT COUNT(*) FROM exhibition_brand WHERE industry_l1 = '' OR industry_l1 IS NULL"
        ).fetchone()[0]
        total = conn.execute("SELECT COUNT(*) FROM exhibition_brand").fetchone()[0]
        log.info(f"  验证: {total - empty_l1}/{total} 品牌已分类 (l1 非空)")
        if empty_l1 > 0:
            log.warning(f"  ⚠ {empty_l1} 品牌仍无 industry_l1")
            sample = conn.execute(
                "SELECT brand_id, name_cn FROM exhibition_brand WHERE industry_l1 = '' LIMIT 10"
            ).fetchall()
            for s in sample:
                log.warning(f"    {s['brand_id']}: {s['name_cn'][:60]}")

    # ── Step 5: L1 distribution report ──
    log.info("\n=== industry_l1 分布 ===")
    l1_dist = conn.execute("""
        SELECT industry_l1, COUNT(*) as cnt
        FROM exhibition_brand
        WHERE industry_l1 != ''
        GROUP BY industry_l1
        ORDER BY cnt DESC
    """).fetchall()
    for r in l1_dist:
        log.info(f"  [{r['cnt']:5d}] {r['industry_l1']}")

    conn.close()
    jufair_conn.close()

    return {
        "total": len(all_brands),
        "jufair_matched": jufair_matched,
        "keyword_matched": keyword_matched,
        "unmatched": unmatched,
        "updates": total_matched,
    }


