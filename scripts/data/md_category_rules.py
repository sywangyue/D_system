def classify_industry_l1(messy_value: str) -> str:
    """将 industry_l1 杂乱值映射到 MD 6 类别之一。

    遍历 MD_CATEGORY_RULES 的每个类别，逐个关键词匹配。
    返回第一个匹配到的类别名称。

    Args:
        messy_value: 原始 industry_l1 字段值

    Returns:
        匹配到的 MD 类别名称；无匹配时返回空字符串 ""
    """
    if not messy_value:
        return ''
    for category, keywords in MD_CATEGORY_RULES.items():
        for kw in keywords:
            if kw in messy_value:
                return category
    return ''


def list_nonempty_categories() -> list[str]:
    """返回所有非空 MD 类别名称列表。

    Returns:
        按定义顺序的类别名称列表
    """
    return list(MD_CATEGORY_RULES.keys())
