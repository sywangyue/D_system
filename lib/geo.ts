/** 与旧看板同一口径：country_cn 为空或为「中国」算国内。 */
export function isDomestic(countryCn: string | null | undefined): boolean {
  const c = (countryCn ?? "").trim()
  return c === "" || c === "中国"
}

/**
 * 把一个品牌落到地图上的一个点。
 * 国内按 city 查 CITY_GEO；海外按 country_cn 查 COUNTRY_GEO。
 * 查不到返回 null（调用方负责计数，不许静默丢）。
 */
export function resolvePoint(brand: {
  country_cn?: string | null
  city?: string | null
}): GeoPoint | null {
  if (isDomestic(brand.country_cn)) {
    const city = (brand.city ?? "").trim()
    const hit = CITY_GEO[city]
    return hit ? { name: city, lon: hit[0], lat: hit[1] } : null
  }
  const country = (brand.country_cn ?? "").trim()
  const hit = COUNTRY_GEO[country]
  return hit ? { name: country, lon: hit[0], lat: hit[1] } : null
}
